#!/usr/bin/env bash
# Starts this ticket's docker compose stack. Run by `orca-lc worktree up --stack` as `stackUp`, with
# ORCA_TICKET, ORCA_WORKTREE and the ticket's *_PORT values exported. See examples/stack/README.md.
# Needs docker with Compose >= 2.24.4, git, and orca-lc on PATH.
set -euo pipefail

# --- Settings: edit here, or set them as prefixes in the stackUp command. -------------------------
# VAR=service:containerPort, space-separated: each Orca port and where it is published.
: "${ORCA_PORT_MAP:=WEB_PORT=web:80 API_PORT=api:8080}"
# Base compose file(s), split on ${COMPOSE_PATH_SEPARATOR:-:}. Unset: Compose's own lookup.
: "${COMPOSE_FILE:=}"
# Named volume holding seed data, and the compose volume key it fills. Unset: no seeding.
: "${SEED_VOLUME:=}"
: "${SEED_TARGET:=}"
# ---------------------------------------------------------------------------------------------------

die() { echo "stack-up: $*" >&2; exit 1; }
: "${ORCA_TICKET:?ORCA_TICKET is unset; run this through orca-lc worktree up --stack}"
: "${ORCA_WORKTREE:?ORCA_WORKTREE is unset; run this through orca-lc worktree up --stack}"
cd "$ORCA_WORKTREE"

# 1. Compose version: ports: !override needs 2.24.4.
ver=$(docker compose version --short) || die "docker compose is not available"
v=${ver#v}; v=${v%%-*}
IFS=. read -r maj min pat _ <<<"$v"
maj=${maj:-0} min=${min:-0} pat=${pat:-0}
case "$maj$min$pat" in *[!0-9]*) die "cannot read docker compose version '$ver'" ;; esac
if (( 10#$maj < 2 || (10#$maj == 2 && (10#$min < 24 || (10#$min == 24 && 10#$pat < 4))) )); then
  die "docker compose $ver is older than 2.24.4, which ports: !override needs; upgrade Docker Compose"
fi

# 2. Project name: <project>-<ticket>.
project=$(orca-lc config project)
[ -n "$project" ] || die "set project in .orca/config.json; it names the compose project"
project=$(printf '%s' "$project" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_-' '-')
name="$project-$ORCA_TICKET"

# 3. Compose files.
files=()
if [ -n "$COMPOSE_FILE" ]; then
  IFS="${COMPOSE_PATH_SEPARATOR:-:}" read -r -a files <<<"$COMPOSE_FILE"
else
  for f in compose.yaml compose.yml docker-compose.yaml docker-compose.yml; do
    [ -f "$f" ] && { files+=("$ORCA_WORKTREE/$f"); break; }
  done
  [ ${#files[@]} -gt 0 ] || die "no compose.yaml in $ORCA_WORKTREE; add one or set COMPOSE_FILE"
  for f in compose.override.yaml compose.override.yml docker-compose.override.yaml docker-compose.override.yml; do
    [ -f "$f" ] && { files+=("$ORCA_WORKTREE/$f"); break; }
  done
fi

# 4. Port map check: every Orca port (the *_PORT lines of .env.local) needs a map entry.
read -r -a map <<<"$ORCA_PORT_MAP"
if [ -f .env.local ]; then
  while IFS='=' read -r var _; do
    found=
    for e in "${map[@]}"; do [ "${e%%=*}" = "$var" ] && found=1; done
    [ -n "$found" ] || die "$var has no entry in ORCA_PORT_MAP; add $var=service:containerPort"
  done < <(grep -E '^[A-Z0-9_]+_PORT=' .env.local || true)
fi
for e in "${map[@]}"; do
  var=${e%%=*}
  case "$e" in *=*:*) ;; *) die "ORCA_PORT_MAP entry '$e' is not VAR=service:containerPort" ;; esac
  [ -n "${!var:-}" ] || die "$var is in ORCA_PORT_MAP but unset; add it to ports in .orca/config.json"
done

# 5. Override file, one ports: !override per service, in map order.
override=$(git -C "$ORCA_WORKTREE" rev-parse --git-path orca-compose.override.yaml)
case "$override" in /*) ;; *) override="$ORCA_WORKTREE/$override" ;; esac
{
  echo "# Generated by stack-up.sh on every run; do not edit."
  echo "services:"
  done_svcs=" "
  for e in "${map[@]}"; do
    rest=${e#*=}; svc=${rest%%:*}
    case "$done_svcs" in *" $svc "*) continue ;; esac
    done_svcs="$done_svcs$svc "
    echo "  $svc:"
    echo "    ports: !override"
    for e2 in "${map[@]}"; do
      r2=${e2#*=}
      [ "${r2%%:*}" = "$svc" ] || continue
      v2=${e2%%=*}
      echo "      - \"${!v2}:${r2#*:}\""
    done
  done
} > "$override"

# 6. Seed, once per ticket.
if [ -n "$SEED_VOLUME" ]; then
  [ -n "$SEED_TARGET" ] || die "SEED_VOLUME is set but SEED_TARGET is not; name the compose volume to fill"
  vol="${name}_$SEED_TARGET"
  if ! docker volume inspect "$vol" >/dev/null 2>&1; then
    docker volume inspect "$SEED_VOLUME" >/dev/null 2>&1 \
      || die "SEED_VOLUME '$SEED_VOLUME' does not exist; create it or fix SEED_VOLUME"
    docker volume create --label "com.docker.compose.project=$name" \
      --label "com.docker.compose.volume=$SEED_TARGET" "$vol" >/dev/null
    if ! docker run --rm -v "$SEED_VOLUME":/from:ro -v "$vol":/to alpine:3.20 cp -a /from/. /to/; then
      docker volume rm "$vol" >/dev/null 2>&1 || true
      die "copying SEED_VOLUME '$SEED_VOLUME' into $vol failed; removed $vol so a retry seeds again"
    fi
  fi
fi

# 7. Up.
args=()
for f in "${files[@]}"; do args+=(-f "$f"); done
docker compose -p "$name" "${args[@]}" -f "$override" up -d --wait

# 8.
echo "stack $name up; override $override"
