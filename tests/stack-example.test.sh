# examples/stack/stack-up.sh and stack-down.sh, run against a stub docker (no Docker needed)
ex="$ORCA_SRC/examples/stack"
log="$TMPDIR/docker.log"
# Stub docker: logs every call; STUB_VERSION answers `compose version --short`; STUB_VOLUMES lists
# the volumes `volume inspect` finds; STUB_RUN_FAIL=1 fails `run`.
cat > "$TMPDIR/bin/docker" <<'EOF'
#!/usr/bin/env bash
echo "$*" >> "$STUB_LOG"
case "$1 $2" in
  "compose version") echo "${STUB_VERSION:-2.29.0}" ;;
  "volume inspect") for v in ${STUB_VOLUMES:-}; do [ "$v" = "$3" ] && exit 0; done; exit 1 ;;
  "run "*) [ "${STUB_RUN_FAIL:-}" = 1 ] && exit 1 ;;
esac
exit 0
EOF
chmod +x "$TMPDIR/bin/docker"
export STUB_LOG="$log"

r=$(new_repo '{"project":"My.Proj","gate":"true"}')
cp "$ex/compose.yaml" "$r/"; git -C "$r" add compose.yaml; git -C "$r" commit -qm compose
printf 'WEB_PORT=3010\nAPI_PORT=3011\n' > "$r/.env.local"
echo .env.local >> "$r/.git/info/exclude"
override=$(cd "$r" && realpath "$(git rev-parse --git-path orca-compose.override.yaml)")

# up [env...] -> runs stack-up.sh in a clean env; output in $out, status in $st, log reset first
up() {
  : > "$log"
  out=$(env -u COMPOSE_FILE -u COMPOSE_PATH_SEPARATOR -u SEED_VOLUME -u SEED_TARGET -u ORCA_PORT_MAP \
    ORCA_TICKET=abc-1 ORCA_WORKTREE="$r" WEB_PORT=3010 API_PORT=3011 "$@" "$ex/stack-up.sh" 2>&1); st=$?
}
down() {
  : > "$log"
  out=$(env ORCA_TICKET=abc-1 ORCA_WORKTREE="$r" "$@" "$ex/stack-down.sh" 2>&1); st=$?
}

# Up: project name, files, override contents, clean tree
up
assert_status "$st" 0 "up failed: $out"
assert_contains "$(cat "$log")" "compose -p my-proj-abc-1 -f $r/compose.yaml -f $override up -d --wait"
case "$override" in "$(realpath "$r/.git")"/*) ;; *) fail "override not under the git dir: $override" ;; esac
assert_eq "$(cat "$override")" '# Generated by stack-up.sh on every run; do not edit.
services:
  web:
    ports: !override
      - "3010:80"
  api:
    ports: !override
      - "3011:8080"'
assert_eq "$(git -C "$r" status --porcelain)" "" "up left the tree dirty"
assert_contains "$out" "stack my-proj-abc-1 up; override $override"

# An unrelated *_PORT in the environment is ignored
up FOO_PORT=1
assert_status "$st" 0 "FOO_PORT broke up: $out"

# Compose's automatic override file is kept, after the base file
echo 'services: {}' > "$r/compose.override.yaml"
up
assert_contains "$(cat "$log")" "-f $r/compose.yaml -f $r/compose.override.yaml -f $override up"
rm "$r/compose.override.yaml"

# COMPOSE_FILE: its files in order, no automatic override
echo 'services: {}' > "$r/a.yaml"; echo 'services: {}' > "$r/b.yaml"; echo 'services: {}' > "$r/compose.override.yaml"
up COMPOSE_FILE=a.yaml:b.yaml
assert_contains "$(cat "$log")" "compose -p my-proj-abc-1 -f a.yaml -f b.yaml -f $override up"
assert_not_contains "$(cat "$log")" "$r/compose.override.yaml"
up COMPOSE_FILE='a.yaml;b.yaml' 'COMPOSE_PATH_SEPARATOR=;'
assert_contains "$(cat "$log")" "-f a.yaml -f b.yaml -f $override up"
rm "$r/a.yaml" "$r/b.yaml" "$r/compose.override.yaml"

# Versions
for v in 5.6.0 2.24.4-desktop.1 v2.24.4; do
  up STUB_VERSION=$v; assert_status "$st" 0 "version $v refused: $out"
done
for v in 2.24.3 2.9.0 1.29.2; do
  up STUB_VERSION=$v
  assert_status "$st" 1 "version $v accepted"
  assert_contains "$out" "2.24.4"
  assert_not_contains "$(cat "$log")" " up "
done

# An Orca port with no map entry, and a mapped variable that is unset
echo DB_PORT=3012 >> "$r/.env.local"
up DB_PORT=3012
assert_status "$st" 1 "unmapped DB_PORT accepted"
assert_contains "$out" "DB_PORT"
printf 'WEB_PORT=3010\nAPI_PORT=3011\n' > "$r/.env.local"
up 'ORCA_PORT_MAP=WEB_PORT=web:80 API_PORT=api:8080 X_PORT=api:9000'
assert_status "$st" 1 "unset X_PORT accepted"
assert_contains "$out" "X_PORT"
assert_not_contains "$(cat "$log")" " up "

# No compose file and no COMPOSE_FILE
mv "$r/compose.yaml" "$r/compose.bak"
up
assert_status "$st" 1 "up ran with no compose file"
mv "$r/compose.bak" "$r/compose.yaml"

# Seed: copied once into <project>_<target>, with Compose's labels
up SEED_VOLUME=seed SEED_TARGET=data STUB_VOLUMES=seed
assert_status "$st" 0 "seed failed: $out"
l=$(cat "$log")
assert_contains "$l" "volume create --label com.docker.compose.project=my-proj-abc-1 --label com.docker.compose.volume=data my-proj-abc-1_data"
assert_contains "$l" "run --rm -v seed:/from:ro -v my-proj-abc-1_data:/to alpine:3.20 cp -a /from/. /to/"
up SEED_VOLUME=seed SEED_TARGET=data 'STUB_VOLUMES=seed my-proj-abc-1_data'
assert_status "$st" 0
assert_not_contains "$(cat "$log")" "volume create"
assert_not_contains "$(cat "$log")" "run --rm"

# Seed volume missing: fails before creating anything
up SEED_VOLUME=seed SEED_TARGET=data
assert_status "$st" 1 "missing seed accepted"
assert_contains "$out" "SEED_VOLUME"
assert_not_contains "$(cat "$log")" "volume create"
assert_not_contains "$(cat "$log")" "run --rm"

# SEED_VOLUME without SEED_TARGET
up SEED_VOLUME=seed STUB_VOLUMES=seed
assert_status "$st" 1 "SEED_VOLUME without SEED_TARGET accepted"
assert_contains "$out" "SEED_TARGET"

# Seed copy fails: the ticket volume is removed after the run
up SEED_VOLUME=seed SEED_TARGET=data STUB_VOLUMES=seed STUB_RUN_FAIL=1
assert_status "$st" 1 "failed copy accepted"
assert_contains "$(sed -n '/^run /,$p' "$log")" "volume rm my-proj-abc-1_data"
assert_not_contains "$(cat "$log")" " up "

# Down
down
assert_status "$st" 0 "down failed: $out"
assert_eq "$(cat "$log")" "compose -p my-proj-abc-1 down -v --remove-orphans"

# project unset: both fail naming it, nothing reaches docker
echo '{"gate":"true"}' > "$r/.orca/config.json"
up
assert_status "$st" 1 "up ran without project"
assert_contains "$out" "project"
assert_eq "$(grep -v '^compose version' "$log")" "" "up reached docker without project"
down
assert_status "$st" 1 "down ran without project"
assert_contains "$out" "project"
assert_eq "$(cat "$log")" "" "down reached docker without project"
